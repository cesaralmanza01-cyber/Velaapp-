export function getValidatedColombianFoods(options?: {
  isCeliac?: boolean;
  category?: 'proteinas' | 'carbohidratos' | 'grasas' | 'frutas' | 'verduras' | 'cereales_tuberculos' | 'vegetales' | string;
  grupo?: 'proteinas' | 'carbohidratos' | 'grasas' | 'frutas' | 'verduras' | 'cereales_tuberculos' | 'vegetales' | string;
  isProduct?: boolean;
  typeTab?: 'todos' | 'alimentos' | 'productos';
}): FoodEquivalenceItem[] {
  let list = COLOMBIAN_FOOD_EQUIVALENCES.map((food) => {
    const isProd =
      Boolean(food.colombianBrand && food.colombianBrand.length > 0 && !food.colombianBrand.includes('mercado local')) ||
      Boolean(food.name.includes('San Martín') || food.name.includes('Alpina') || food.name.includes('Colanta') || food.name.includes('Taeq') || food.name.includes('Friko') || food.name.includes('Pietrán'));

    return {
      ...food,
      nombre: food.nombre || food.name,
      porcion: food.porcion || food.portion,
      proteina_100g: food.proteina_100g ?? food.macrosPor100g.proteinaG,
      carbo_100g: food.carbo_100g ?? food.macrosPor100g.carbohidratoG,
      grasa_100g: food.grasa_100g ?? food.macrosPor100g.grasaG,
      is_product: food.is_product !== undefined ? food.is_product : isProd,
    };
  }).filter((f) => f.estado_validacion === 'validado');

  if (options?.isCeliac) {
    list = list.filter((f) => f.glutenFree !== false);
  }

  const targetCategory = options?.category || options?.grupo;
  if (targetCategory && targetCategory !== 'todos') {
    const norm = targetCategory.toLowerCase();
    list = list.filter((f) => {
      const g = (f.grupo || '').toLowerCase();
      const c = (f.category || '').toLowerCase();
      if (norm.includes('prot')) return g.includes('prot') || c.includes('prot');
      if (norm.includes('cereal') || norm.includes('carb') || norm.includes('tuber')) return g.includes('cereal') || c.includes('carb') || g.includes('carb');
      if (norm.includes('frut')) return g.includes('frut') || c.includes('frut');
      if (norm.includes('veg') || norm.includes('verd')) return g.includes('veg') || c.includes('verd') || g.includes('verd');
      if (norm.includes('gras')) return g.includes('gras') || c.includes('gras');
      return g === norm || c === norm;
    });
  }

  if (options?.typeTab === 'alimentos') {
    list = list.filter((f) => !f.is_product);
  } else if (options?.typeTab === 'productos') {
    list = list.filter((f) => f.is_product);
  }

  return list;
}

export function getAllFoodFamiliesForGroup(grupo: string): string[] {
  const foods = getValidatedColombianFoods({ grupo });
  const families = new Set<string>();
  foods.forEach((f) => {
    if (f.familia) families.add(f.familia);
  });
  return Array.from(families);
}

export function getFoodById(id: string): FoodEquivalenceItem | undefined {
  const item = COLOMBIAN_FOOD_EQUIVALENCES.find((f) => f.id === id);
  if (!item) return undefined;
  return {
    ...item,
    nombre: item.nombre || item.name,
    porcion: item.porcion || item.portion,
    proteina_100g: item.proteina_100g ?? item.macrosPor100g.proteinaG,
    carbo_100g: item.carbo_100g ?? item.macrosPor100g.carbohidratoG,
    grasa_100g: item.grasa_100g ?? item.macrosPor100g.grasaG,
    is_product: item.is_product ?? Boolean(item.colombianBrand),
  };
}

export function getFoodsByGroup(grupo: string): FoodEquivalenceItem[] {
  return getValidatedColombianFoods({ grupo });
}

export function getPortionDescription(food: FoodEquivalenceItem, count: number): string {
  const countStr = count.toString();
  if (food.porciones && food.porciones[countStr]) {
    return food.porciones[countStr];
  }
  if (count === 1) return food.portion || food.porcion || '';
  return `${count}x (${food.portion || food.porcion})`;
}

